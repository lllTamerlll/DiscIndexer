using System.Collections.Generic;

namespace Cost_Calculation
{
    /// <summary>
    /// Коэффициенты, определяющие советы «что выбросить» и «что фармить».
    /// Собраны в одном месте, чтобы их можно было осознанно настраивать, а не
    /// искать «магические числа», разбросанные по разным файлам. Значения —
    /// экспертная настройка эвристик, а не игровые константы.
    /// </summary>
    public static class Tuning
    {
        // ── Авто-отметка на распыление (AutoMarkService) ─────────────────
        // Диск помечается, если его «польза» ниже порога по группе (одинаковые
        // слот + главный стат + сет). Порог — не чистое среднее группы, а смесь
        // среднего группы и среднего по пулу (тот же слот+главстат по всем сетам):
        //   base = (n·avg_группы + K·avg_пула) / (n + K),  порог = round(base·σ).
        // Малые группы (n мал) подтягиваются к общему пулу и соотносятся между
        // собой; большие группы (n велик) опираются на собственное среднее.
        // K — «псевдо-вес» пула: чем больше, тем сильнее сжатие к общей линейке.
        public const double PoolPseudoWeight = 5;

        // Веса векторов внутри сета (кураторская оценка «под что сет нужен»).
        // Влияют на авто-метку «По всем пресетам» и совет по фарму:
        //  • приоритетный вектор — основной (полный вес); хорош в нём → диск цел;
        //  • «в принципе можно» — слабее: в авто-метке диск спасается, только если
        //    в этом векторе он ЯВНО силён (порог × AcceptableStrictness), а в
        //    совете по фарму отставание учитывается с пониженным весом;
        //  • «нежелательно» — вектор не участвует в расчётах вовсе.
        public const double VectorWeightPriority   = 1.0;
        public const double VectorWeightAcceptable = 0.5;
        // Насколько строже планка «диск явно силён» для вектора «можно»: чтобы
        // спасти диск от выброса, он должен превзойти обычный порог в столько раз.
        public const double AcceptableStrictness = 1.3;

        // Структурный гандикап трёхстатника при сравнении с четырёхстатной
        // «стеной» (этап 2 авто-метки). Трёхстатник имеет на одну суммарную
        // прокатку меньше (8 против 9 при +15), т.к. одна уходит на вскрытие
        // 4-го субстата. Эта прибавка к его пользе уравнивает структурный недобор,
        // чтобы перекрытие четырёхстатниками оценивалось честно, а не штрафовало
        // диск просто за тип. Сами трёхстатники между собой сравниваются без
        // гандикапа (недобор у всех одинаков).
        public const int ThreeStatHandicap = 1;

        // ── Советы по фарму (AnalyticsService) ───────────────────────────
        // Вес «двухчастного» спроса относительно «четырёхчастного». Первичный
        // сигнал к фарму — спрос на 4 части (вес 1), 2 части добавляют сверху.
        // Вес подобран так, чтобы суммарное число владельцев могло перевесить:
        // напр. 2×4ч + 3×2ч (= 2 + 0.6·3 = 3.8) приоритетнее 3×4ч + 0 (= 3.0),
        // но при этом один владелец 4 частей всегда дороже владельца 2 частей.
        public const double BonusPieceWeight = 0.6;

        // Дефицитность сета: фарм нужнее, когда хороших дисков сета мало, и не
        // нужен, когда их уже много. Множитель = ComfortableSetSize / число
        // дисков, зажатый в [Floor, Cap]. Вместе с отставанием по пользе даёт
        // критерий «много и качественно — не фармить; мало и слабо — фармить».
        public const double FarmComfortableSetSize = 6;   // нейтральная точка
        public const double FarmScarcityFloor = 0.4;       // потолок гашения
        public const double FarmScarcityCap = 1.8;         // потолок буста

        // Надбавка к ценности данжа, когда оба его сета нужны примерно поровну
        // (фарм эффективнее — за один заход добываются два полезных сета).
        public const double BalanceBonus = 0.6;

        // Порог «равномерности»: данж считается сбалансированным, если меньший
        // спрос составляет не менее этой доли от большего.
        public const double BalancedRatioThreshold = 0.6;

        // ── Аналитика качества (AnalyticsPage) ───────────────────────────
        // Потолок шкалы «пользы» по каждому вектору (индекс: 0 — Атакер,
        // 1 — Разрушение, 2 — Аномалия): столбик в 100% высоты соответствует
        // этому числу суммарных прокачек профильных субстатов.
        public static readonly IReadOnlyList<double> PresetMax = new double[] { 8, 8, 7 };
    }
}
