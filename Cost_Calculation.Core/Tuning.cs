using System.Collections.Generic;

namespace Cost_Calculation
{
    /// <summary>
    /// Коэффициенты, определяющие советы «что выбросить» и «что фармить».
    /// Собраны в одном месте, чтобы их можно было осознанно настраивать, а не
    /// искать «магические числа», разбросанные по разным файлам. Значения —
    /// экспертная настройка эвристик, а не игровые константы.
    /// </summary>
    public static class Tuning
    {
        // ── Авто-отметка на распыление (AutoMarkService) ─────────────────
        // Диск помечается, если его «польза» ниже средней по группе (одинаковые
        // слот + главный стат + сет), умноженной на порог. Чем больше группа,
        // тем выше планка: есть из чего выбирать, значит требования строже.
        public const double AutoMarkCutoffSmall  = 1.05; // группа ≤ 3 дисков
        public const double AutoMarkCutoffMedium = 1.10; // группа из 4 дисков
        public const double AutoMarkCutoffLarge  = 1.15; // группа ≥ 5 дисков

        // ── Советы по фарму (AnalyticsService) ───────────────────────────
        // Вес «двухчастного» спроса относительно «четырёхчастного»: сет на 2
        // части — приятный бонус, поэтому учитывается с понижающим весом.
        public const double BonusPieceWeight = 0.35;

        // Надбавка к ценности данжа, когда оба его сета нужны примерно поровну
        // (фарм эффективнее — за один заход добываются два полезных сета).
        public const double BalanceBonus = 0.6;

        // Порог «равномерности»: данж считается сбалансированным, если меньший
        // спрос составляет не менее этой доли от большего.
        public const double BalancedRatioThreshold = 0.6;

        // ── Аналитика качества (AnalyticsPage) ───────────────────────────
        // Потолок шкалы «пользы» по каждому вектору (индекс: 0 — Атакер,
        // 1 — Разрушение, 2 — Аномалия): столбик в 100% высоты соответствует
        // этому числу суммарных прокачек профильных субстатов.
        public static readonly IReadOnlyList<double> PresetMax = new double[] { 8, 8, 7 };
    }
}
